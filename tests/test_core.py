"""Moteur de mO2FLATTENER sur une fausse instance MO2 : priorités, filtres, Root Builder, copies APFS."""
import os
import sys
import tempfile
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "src"))

import mo2_flattener_core as core  # noqa: E402


class TestFlattener(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.base = Path(self.tmp.name)
        self.mo2 = self.base / "MO2"
        self.profile = self.mo2 / "profiles" / "Default"
        self.profile.mkdir(parents=True)
        self.dest = self.base / "Game"

    def tearDown(self):
        self.tmp.cleanup()

    def put(self, rel: str, text: str = "x") -> Path:
        path = self.mo2 / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
        return path

    def modlist(self, *lines: str) -> Path:
        path = self.profile / "modlist.txt"
        path.write_text("# This file was automatically generated by Mod Organizer.\n" + "\n".join(lines) + "\n")
        return path

    def plan(self, modlist: Path) -> dict:
        return {str(dst.relative_to(self.dest)): src for src, dst in core.build_tasks(self.mo2, modlist, self.dest)}

    def test_modlist_order_and_markers(self):
        ml = self.modlist("+High", "-Disabled", "*DLC: Dawnguard", "+Tools_separator", "+Low")
        self.assertEqual(core.parse_modlist(ml), ["Low", "High"])

    def test_higher_priority_wins_case_insensitively(self):
        self.put("mods/Low/Textures/Sky.dds", "low")
        self.put("mods/High/textures/sky.DDS", "high")
        plan = self.plan(self.modlist("+High", "+Low"))
        self.assertEqual(len(plan), 1)
        (rel, src), = plan.items()
        self.assertEqual(src.read_text(), "high")
        self.assertEqual(rel, "Data/textures/sky.DDS")

    def test_original_case_kept(self):
        self.put("mods/A/SKSE/Plugins/EngineFixes.dll")
        self.assertIn("Data/SKSE/Plugins/EngineFixes.dll", self.plan(self.modlist("+A")))

    def test_overwrite_beats_mods(self):
        self.put("mods/A/Interface/x.swf", "mod")
        self.put("overwrite/interface/X.swf", "overwrite")
        plan = self.plan(self.modlist("+A"))
        self.assertEqual([s.read_text() for s in plan.values()], ["overwrite"])

    def test_disabled_and_hidden_ignored(self):
        self.put("mods/Off/a.esp")
        self.put("mods/On/b.esp")
        self.put("mods/On/c.esp.mohidden")
        self.put("mods/On/meta.ini")
        self.put("mods/On/readme.txt")
        self.put("mods/On/fomod/ModuleConfig.xml")
        self.assertEqual(set(self.plan(self.modlist("+On", "-Off"))), {"Data/b.esp"})

    def test_root_builder(self):
        self.put("mods/SKSE/Root/skse64_loader.exe")
        self.put("mods/SKSE/Scripts/Actor.pex")
        self.assertEqual(set(self.plan(self.modlist("+SKSE"))), {"skse64_loader.exe", "Data/Scripts/Actor.pex"})

    def test_nested_data_folder(self):
        self.put("mods/Wrapped/Data/Meshes/a.nif")
        self.assertEqual(set(self.plan(self.modlist("+Wrapped"))), {"Data/Meshes/a.nif"})

    def test_stock_game_is_lowest(self):
        stock = self.base / "STOCK GAME"
        (stock / "Data").mkdir(parents=True)
        (stock / "Data" / "Skyrim.esm").write_text("vanilla")
        (stock / "SkyrimSE.exe").write_text("exe")
        self.put("mods/Cleaned/Skyrim.esm", "cleaned")
        plan = self.plan(self.modlist("+Cleaned"))
        self.assertEqual(plan["Data/Skyrim.esm"].read_text(), "cleaned")
        self.assertIn("SkyrimSE.exe", plan)

    def test_stop_returns_nothing(self):
        self.put("mods/A/a.esp")
        self.assertEqual(core.build_tasks(self.mo2, self.modlist("+A"), self.dest, lambda: True), [])

    def test_clone_is_independent(self):
        src = self.put("mods/A/a.esp", "original")
        dst = self.dest / "Data" / "a.esp"
        method = core.optimized_copy_file(src, dst, use_hardlinks=False)
        self.assertIn(method, ("clone", "copy"))
        dst.write_text("edited by a tool")
        self.assertEqual(src.read_text(), "original")
        self.assertNotEqual(os.stat(src).st_ino, os.stat(dst).st_ino)

    def test_copy_replaces_existing(self):
        src = self.put("mods/A/a.esp", "new")
        dst = self.dest / "Data" / "a.esp"
        dst.parent.mkdir(parents=True)
        dst.write_text("old")
        core.optimized_copy_file(src, dst, use_hardlinks=True)
        self.assertEqual(dst.read_text(), "new")


if __name__ == "__main__":
    unittest.main()
