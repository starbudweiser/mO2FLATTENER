const parent = (p) => { const n = normalize(p); return n.slice(0, n.lastIndexOf("/")) || "/"; };

function scanProfiles(mo2Base) {
  let profilesDir = `${normalize(mo2Base)}/profiles`;
  if (!fs.isDir(profilesDir) && fs.isDir(`${parent(mo2Base)}/profiles`)) profilesDir = `${parent(mo2Base)}/profiles`;
  ui.profile.innerHTML = "";
  if (!fs.isDir(profilesDir)) {
    log(`${t("warn_no_profiles")} ${mo2Base}`);
    return;
  }
  const profiles = [...fs.node(profilesDir).dirs.keys()];
  for (const p of profiles) ui.profile.add(new Option(p, p));
  if (profiles.length) { ui.profile.selectedIndex = 0; onProfileSelected(); }
}

function onProfileSelected() {
  const mo2 = ui.mo2.value.trim();
  const prof = ui.profile.value.trim();
  if (mo2 && prof) {
    let target = `${normalize(mo2)}/profiles/${prof}/modlist.txt`;
    const alt = `${parent(mo2)}/profiles/${prof}/modlist.txt`;
    if (!fs.isFile(target) && fs.isFile(alt)) target = alt;
    if (fs.isFile(target)) {
      ui.modlist.value = target;
      ui.status.textContent = `Skyrim SE/AE • ${prof}`;
    }
  }
}
