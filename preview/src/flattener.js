// ------------------------------------------------------------------ Moteur de filtrage (miroir Python)
function splitextLower(name) {
  const lower = name.toLowerCase();
  let lead = 0;
  while (lower[lead] === ".") lead++;
  const i = lower.lastIndexOf(".");
  return i >= lead ? lower.slice(i) : ""; // os.path.splitext ignore les points de tête
}
function isIgnoredFile(filename, isDataRoot = false) {
  if (IGNORED_FILES.has(filename)) return true;
  const lower = filename.toLowerCase();
  if (lower.endsWith(".mohidden")) return true;
  const ext = splitextLower(filename);
  if (IGNORED_EXTENSIONS.has(ext)) return true;
  return isDataRoot && IGNORED_ROOT_FILE_EXTENSIONS.has(ext);
}
function isIgnoredDir(dirname) {
  const lower = dirname.toLowerCase();
  return IGNORED_DIRS.has(lower) || IGNORED_DATA_ROOT_DIRS.has(lower) || lower.endsWith(".mohidden");
}
function filterInPlace(arr, keep) {
  const kept = arr.filter(keep);
  arr.splice(0, arr.length, ...kept);
}
const rel = (full, base) => full.slice(normalize(base).length + 1);
const pjoin = (a, b) => { const n = normalize(a); return n === "" || n === "." ? b : `${n}/${b}`; };

function parseModlist(path) {
  const lines = (MODLISTS[normalize(path)] ?? []).map((l) => l.trim()).filter(Boolean);
  return lines.reverse().filter((l) => l.startsWith("+")).map((l) => l.slice(1).trim()).filter(Boolean);
}

async function runWorker(cfg) {
  const w = worker;
  const failAt = $("pv-error").checked ? 0.4 : -1;
  try {
    log(t("log_analyzing", { name: basename(cfg.modlist) }));
    const activeMods = parseModlist(cfg.modlist);

    let stockGameDir = null;
    if (fs.isDir(`${parent(cfg.mo2)}/STOCK GAME`)) stockGameDir = `${parent(cfg.mo2)}/STOCK GAME`;
    else if (fs.isDir(`${cfg.mo2}/STOCK GAME`)) stockGameDir = `${cfg.mo2}/STOCK GAME`;
    const modsDir = `${cfg.mo2}/mods`;
    const overwriteDir = `${cfg.mo2}/overwrite`;
    const profileDir = parent(cfg.modlist);
    const destData = `${cfg.dest}/Data`;

    log(t("log_root_dir", { path: cfg.dest }));
    log(t("log_data_dir", { path: destData }));
    log(t("log_filters"));
    log(t("log_indexing_ram"));
    await sleep(250);

    const dataMap = new Map();
    const rootMap = new Map();

    // 1. STOCK GAME
    if (stockGameDir) {
      log(t("log_indexing_stock", { name: basename(stockGameDir) }));
      for (const [root, dirs, files] of fs.walk(stockGameDir)) {
        if (w.stopped) break;
        filterInPlace(dirs, (d) => !isIgnoredDir(d));
        for (const f of files) {
          const full = `${root}/${f}`;
          const parts = rel(full, stockGameDir).split("/");
          const isData = parts[0].toLowerCase() === "data";
          const isRootData = isData && parts.length === 2;
          if (isIgnoredFile(f, isRootData)) continue;
          if (isData) {
            const sub = parts.slice(1);
            if (sub.length && IGNORED_DATA_ROOT_DIRS.has(sub[0].toLowerCase())) continue;
            dataMap.set(sub.join("/").toLowerCase(), full);
          } else rootMap.set(parts.join("/").toLowerCase(), full);
        }
      }
    }
    await sleep(150);
    if (w.stopped) return finish("stopped");

    // 2. Mods
    for (const modName of activeMods) {
      if (w.stopped) break;
      const modPath = `${modsDir}/${modName}`;
      if (!fs.isDir(modPath) || isIgnoredDir(modName)) continue;

      const rootBuilder = `${modPath}/Root`;
      if (fs.isDir(rootBuilder)) {
        for (const [root, dirs, files] of fs.walk(rootBuilder)) {
          filterInPlace(dirs, (d) => !isIgnoredDir(d));
          for (const f of files) if (!isIgnoredFile(f)) rootMap.set(rel(`${root}/${f}`, rootBuilder).toLowerCase(), `${root}/${f}`);
        }
      }

      let src = modPath;
      if (fs.isDir(`${modPath}/Data`) && !fs.isDir(`${modPath}/textures`) && !fs.isDir(`${modPath}/meshes`)) src = `${modPath}/Data`;
      for (const [root, dirs, files] of fs.walk(src)) {
        filterInPlace(dirs, (d) => !isIgnoredDir(d));
        if (src === modPath) filterInPlace(dirs, (d) => d !== "Root");
        for (const f of files) {
          const full = `${root}/${f}`;
          const parts = rel(full, src).split("/");
          if (isIgnoredFile(f, parts.length === 1)) continue;
          if (IGNORED_DATA_ROOT_DIRS.has(parts[0].toLowerCase())) continue;
          dataMap.set(parts.join("/").toLowerCase(), full);
        }
      }
      await sleep(60);
    }
    if (w.stopped) return finish("stopped");

    // 3. Overwrite
    if (fs.isDir(overwriteDir)) {
      for (const [root, dirs, files] of fs.walk(overwriteDir)) {
        filterInPlace(dirs, (d) => !isIgnoredDir(d));
        for (const f of files) {
          const full = `${root}/${f}`;
          const parts = rel(full, overwriteDir).split("/");
          if (isIgnoredFile(f, parts.length === 1)) continue;
          if (IGNORED_DATA_ROOT_DIRS.has(parts[0].toLowerCase())) continue;
          dataMap.set(parts.join("/").toLowerCase(), full);
        }
      }
    }

    const tasks = [];
    for (const [r, s] of rootMap) tasks.push([s, `${cfg.dest}/${r}`]);
    for (const [r, s] of dataMap) tasks.push([s, `${destData}/${r}`]);
    const total = tasks.length;
    log(t("log_index_complete", { total }));
    log(t("log_copy_start"));

    // Copie multi-thread simulée : ~40 fichiers par image
    let copied = 0;
    const failIndex = failAt > 0 ? Math.floor(total * failAt) : -1;
    for (let i = 0; i < total; i++) {
      if (i % 40 === 0) await sleep(16);
      if (w.stopped) return finish("stopped");
      const [s, d] = tasks[i];
      if (i === failIndex) {
        const err = `[Errno 28] No space left on device: '${d}'`;
        log(t("log_copy_err", { src: basename(s), dst: basename(d), err }));
        if (cfg.stopOnError) {
          w.stopped = true;
          return finish("error", t("log_copy_abort_err", { err }));
        }
      } else copied++;
      if (copied % 100 === 0 || copied === total) {
        setProgress(Math.floor((copied / total) * 95));
        if (copied % 500 === 0) log(t("log_progress", { current: copied, total }));
      }
    }
    if (w.stopped) return finish("stopped");

    // Déploiement des configurations
    if (cfg.copyPlugins) {
      const srcPlugins = `${profileDir}/plugins.txt`;
      if (fs.isFile(srcPlugins)) log(t("log_plugin_deployed", { path: pjoin(cfg.pluginsDest, "plugins.txt") }));
    }
    if (cfg.copyInis) {
      for (const iniName of ["skyrim.ini", "skyrimprefs.ini"]) {
        let srcIni = `${profileDir}/${iniName}`;
        if (!fs.isFile(srcIni)) {
          const match = [...(fs.node(profileDir)?.files.keys() ?? [])].find((f) => f.toLowerCase() === iniName);
          if (match) srcIni = `${profileDir}/${match}`;
        }
        if (fs.isFile(srcIni)) log(t("log_ini_deployed", { name: basename(srcIni) }));
      }
    }
    setProgress(100);
    log(t("log_success", { count: copied }));
    return finish("ok");
  } catch (e) {
    return finish("error", String(e.message ?? e));
  }
}

// ------------------------------------------------------------------ Lancement / fin
async function startProcess() {
  if (worker?.running) return;
  const mo2 = normalize(ui.mo2.value) || ".";
  const modlist = normalize(ui.modlist.value);
  const dest = normalize(ui.dest.value);
  const s = std();
  const critical = (key) => messageBox(host, { kind: "critical", title: t("err_title"), text: t(key),
    buttons: [{ label: s.ok, value: true, default: true }], buttonClass: "fl-msgbtn" });

  // Path("") vaut "." côté Python : un dossier existant.
  if (mo2 !== "." && !fs.isDir(mo2)) return critical("err_mo2_invalid");
  if (!modlist || !fs.isFile(modlist)) return critical("err_modlist_invalid");
  if (!basename(dest)) return critical("err_dest_empty");

  ui.run.disabled = true;
  ui.stop.disabled = false;
  setProgress(0);
  ui.status.textContent = t("header_status_running");
  worker = { stopped: false, running: true };
  await runWorker({
    mo2, modlist, dest,
    stopOnError: ui.stoperr.checked,
    copyPlugins: ui.cplugins.checked, pluginsDest: ui.plugins.value.trim(),
    copyInis: ui.cinis.checked,
  });
}

async function finish(kind, message) {
  worker.running = false;
  ui.run.disabled = false;
  ui.stop.disabled = true;
  const box = (k, title, text) => messageBox(host, { kind: k, title, text,
    buttons: [{ label: std().ok, value: true, default: true }], buttonClass: "fl-msgbtn" });
  if (kind === "ok") {
    ui.status.textContent = t("header_status_done");
    await box("information", t("success_title"), t("success_msg"));
  } else if (kind === "stopped") {
    ui.status.textContent = t("header_status_stopped");
    await box("warning", t("err_title"), t("stop_msg"));
  } else {
    ui.status.textContent = t("header_status_error");
    log(`\n[ERREUR CRITIQUE] ${message}`);
    await box("critical", t("err_title"), message);
  }
}

ui.run.addEventListener("click", startProcess);
ui.stop.addEventListener("click", () => {
  if (worker?.running) {
    ui.stop.disabled = true;
    ui.status.textContent = t("header_status_stopped");
    log(t("log_interrupt_requested"));
    worker.stopped = true;
  }
});

