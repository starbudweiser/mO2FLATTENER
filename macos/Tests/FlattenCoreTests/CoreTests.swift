// Moteur de mO2FLATTENER sur une fausse instance MO2 : priorités, filtres, Root Builder, copies APFS (port de tests/test_core.py).
import XCTest
@testable import FlattenCore

final class CoreTests: XCTestCase {
    var base = "", mo2 = "", profile = "", dest = ""

    override func setUp() {
        base = (NSTemporaryDirectory() + "mo2f_" + UUID().uuidString).replacingOccurrences(of: "//", with: "/")
        base = realPath(base.isEmpty ? "/tmp" : base)
        mo2 = base + "/MO2"; profile = mo2 + "/profiles/Default"; dest = base + "/Game"
        try? FileManager.default.createDirectory(atPath: profile, withIntermediateDirectories: true)
        base = realPath(base)
    }
    override func tearDown() { try? FileManager.default.removeItem(atPath: base) }

    @discardableResult func put(_ rel: String, _ text: String = "x") -> String {
        let p = mo2 + "/" + rel
        try? FileManager.default.createDirectory(atPath: pyParent(p), withIntermediateDirectories: true)
        try? text.write(toFile: p, atomically: false, encoding: .utf8)
        return p
    }
    func modlist(_ lines: String...) -> String {
        let p = profile + "/modlist.txt"
        try? ("# This file was automatically generated by Mod Organizer.\n" + lines.joined(separator: "\n") + "\n").write(toFile: p, atomically: false, encoding: .utf8)
        return p
    }
    func plan(_ ml: String) throws -> [String: String] {
        var out: [String: String] = [:]
        for t in try buildTasks(mo2Dir: mo2, modlistFile: ml, destGameRoot: dest) { out[String(t.dst.dropFirst(dest.count + 1))] = t.src }
        return out
    }
    func read(_ p: String) -> String { (try? String(contentsOfFile: p, encoding: .utf8)) ?? "" }

    func testModlistOrderAndMarkers() throws {
        let ml = modlist("+High", "-Disabled", "*DLC: Dawnguard", "+Tools_separator", "+Low")
        XCTAssertEqual(try parseModlist(ml), ["Low", "High"])
    }

    func testHigherPriorityWinsCaseInsensitively() throws {
        put("mods/Low/Textures/Sky.dds", "low")
        put("mods/High/textures/sky.DDS", "high")
        let p = try plan(modlist("+High", "+Low"))
        XCTAssertEqual(p.count, 1)
        XCTAssertEqual(read(p["Data/textures/sky.DDS"]!), "high")
    }

    func testOriginalCaseKept() throws {
        put("mods/A/SKSE/Plugins/EngineFixes.dll")
        XCTAssertNotNil(try plan(modlist("+A"))["Data/SKSE/Plugins/EngineFixes.dll"])
    }

    func testOverwriteBeatsMods() throws {
        put("mods/A/Interface/x.swf", "mod")
        put("overwrite/interface/X.swf", "overwrite")
        XCTAssertEqual(try plan(modlist("+A")).values.map(read), ["overwrite"])
    }

    func testDisabledAndHiddenIgnored() throws {
        put("mods/Off/a.esp"); put("mods/On/b.esp"); put("mods/On/c.esp.mohidden"); put("mods/On/meta.ini")
        put("mods/On/readme.txt"); put("mods/On/fomod/ModuleConfig.xml")
        XCTAssertEqual(Set(try plan(modlist("+On", "-Off")).keys), ["Data/b.esp"])
    }

    func testRootBuilder() throws {
        put("mods/SKSE/Root/skse64_loader.exe"); put("mods/SKSE/Scripts/Actor.pex")
        XCTAssertEqual(Set(try plan(modlist("+SKSE")).keys), ["skse64_loader.exe", "Data/Scripts/Actor.pex"])
    }

    func testNestedDataFolder() throws {
        put("mods/Wrapped/Data/Meshes/a.nif")
        XCTAssertEqual(Set(try plan(modlist("+Wrapped")).keys), ["Data/Meshes/a.nif"])
    }

    func testStockGameIsLowest() throws {
        let stock = base + "/STOCK GAME"
        try FileManager.default.createDirectory(atPath: stock + "/Data", withIntermediateDirectories: true)
        try "vanilla".write(toFile: stock + "/Data/Skyrim.esm", atomically: false, encoding: .utf8)
        try "exe".write(toFile: stock + "/SkyrimSE.exe", atomically: false, encoding: .utf8)
        put("mods/Cleaned/Skyrim.esm", "cleaned")
        let p = try plan(modlist("+Cleaned"))
        XCTAssertEqual(read(p["Data/Skyrim.esm"]!), "cleaned")
        XCTAssertNotNil(p["SkyrimSE.exe"])
    }

    func testStopReturnsNothing() throws {
        put("mods/A/a.esp")
        XCTAssertEqual(try buildTasks(mo2Dir: mo2, modlistFile: modlist("+A"), destGameRoot: dest, stopped: { true }), [])
    }

    func testIgnoreRules() {
        XCTAssertTrue(isIgnoredFile("meta.ini")); XCTAssertFalse(isIgnoredFile("META.INI"))
        XCTAssertTrue(isIgnoredFile("a.PDB")); XCTAssertTrue(isIgnoredFile("readme.TXT", isDataRoot: true))
        XCTAssertFalse(isIgnoredFile("readme.txt")); XCTAssertTrue(isIgnoredFile(".ds_store", isDataRoot: true))  // fichier du Finder, ignoré partout
        // fichiers « ._ » des disques exFAT et dossier __MACOSX : jamais copiés (plantage SKSE sur « ._xxx.dll »)
        XCTAssertTrue(isIgnoredFile("._EngineFixes.dll")); XCTAssertTrue(isIgnoredFile(".DS_Store"))
        XCTAssertFalse(isIgnoredFile("_patch.esp")); XCTAssertFalse(isIgnoredFile(".hidden.ini"))
        XCTAssertTrue(isIgnoredDir("__MACOSX"))
        XCTAssertTrue(isIgnoredDir("FOMOD")); XCTAssertTrue(isIgnoredDir("x.mohidden")); XCTAssertFalse(isIgnoredDir("Textures"))
        XCTAssertEqual(pySplitExt("a.b.c").ext, ".c"); XCTAssertEqual(pySplitExt(".hidden").ext, ""); XCTAssertEqual(pySplitExt("..x.y").ext, ".y")
    }

    func testCloneIsIndependent() throws {
        let src = put("mods/A/a.esp", "original")
        let dst = dest + "/Data/a.esp"
        let method = try optimizedCopyFile(src, dst, useHardlinks: false)
        XCTAssertTrue(["clone", "copy"].contains(method))
        try "edited by a tool".write(toFile: dst, atomically: false, encoding: .utf8)
        XCTAssertEqual(read(src), "original")
        var a = stat(), b = stat(); stat(src, &a); stat(dst, &b)
        XCTAssertNotEqual(a.st_ino, b.st_ino)
    }

    func testCopyReplacesExisting() throws {
        let src = put("mods/A/a.esp", "new")
        let dst = dest + "/Data/a.esp"
        try FileManager.default.createDirectory(atPath: dest + "/Data", withIntermediateDirectories: true)
        try "old".write(toFile: dst, atomically: false, encoding: .utf8)
        try optimizedCopyFile(src, dst, useHardlinks: true)
        XCTAssertEqual(read(dst), "new")
    }

    func testMissingSourceReportsPythonStyleError() {
        XCTAssertThrowsError(try optimizedCopyFile(base + "/nope", dest + "/x", useHardlinks: false)) {
            XCTAssertEqual("\($0)", "[Errno 2] No such file or directory: '\(base)/nope'")
        }
    }

    func testFullFlattenWithPluginsAndInis() throws {
        put("mods/A/Meshes/a.nif", "nif"); put("mods/B/meshes/A.NIF", "nif-b")
        try "plugins".write(toFile: profile + "/plugins.txt", atomically: false, encoding: .utf8)
        try "ini".write(toFile: profile + "/Skyrim.ini", atomically: false, encoding: .utf8)
        var o = FlattenOptions(mo2Dir: mo2, modlistFile: modlist("+B", "+A"), destGameRoot: dest)
        o.copyPlugins = true; o.pluginsDest = base + "/AppData"; o.copyInis = true; o.inisDest = base + "/Docs"
        var lines: [String] = [], last = 0
        var ev = FlattenEvents(); ev.log = { lines.append($0) }; ev.progress = { last = $0 }
        I18n.setLang("fr")
        guard case .finished(let n) = Flattener().run(o, ev) else { return XCTFail("pas terminé") }
        XCTAssertEqual(n, 1)
        XCTAssertEqual(read(dest + "/Data/meshes/A.NIF"), "nif-b")  // B est plus haut dans la liste : il gagne
        XCTAssertEqual(read(base + "/AppData/plugins.txt"), "plugins")
        XCTAssertEqual(read(base + "/Docs/Skyrim.ini"), "ini")
        XCTAssertEqual(last, 100)
        XCTAssertTrue(lines.last!.contains("[SUCCÈS]"))
    }
}
